"""
Задача 2. АО "Прицеп" - прицепы (x1, в тыс. шт.) и кормораздатчики (x2, в тыс. шт.).

Цена:        40.3 и 74.3 тыс. руб.
Себестоимость: 34.66 и 63.9 тыс. руб.
Спрос на прицепы: x1 >= 1.2 (тыс. шт. в год)

Расход на 1000 изделий:
  сталь:  1615*x1 + 2022*x2 <= 25000 (т)
  чугун:   385*x1 +  478*x2 <=  4500 (т)

Решаем три подзадачи: а) max количество, б) max выручка, в) min себестоимость.
"""

from scipy.optimize import linprog

A_ub = [
    [1615, 2022],  # сталь
    [385, 478],    # чугун
]
b_ub = [25000, 4500]
bounds = [(1.2, None), (0, None)]  # x1 >= 1.2 (спрос), x2 >= 0


def solve(c, label, maximize=True):
    coeffs = [-v for v in c] if maximize else c
    res = linprog(coeffs, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method="highs")
    value = -res.fun if maximize else res.fun
    print(f"--- {label} ---")
    print(f"x1 (прицепы, тыс.шт) = {res.x[0]:.3f}")
    print(f"x2 (кормораздатчики, тыс.шт) = {res.x[1]:.3f}")
    print(f"Значение целевой функции = {value:.2f}\n")


# а) максимальное количество изделий: max (x1 + x2)
solve([1, 1], "а) максимум количества изделий", maximize=True)

# б) максимальная выручка: max (40.3*x1 + 74.3*x2)
solve([40.3, 74.3], "б) максимум выручки", maximize=True)

# в) минимальная себестоимость: min (34.66*x1 + 63.9*x2)
solve([34.66, 63.9], "в) минимум себестоимости", maximize=False)
