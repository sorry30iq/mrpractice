"""
Задача 1. АО "Прицеп" - совковые (x1) и штыковые (x2) лопаты.

Расход ресурсов:
  совковая: 0.04 листа металла, 0.004 м3 древесины, цена 60 руб.
  штыковая: 0.02 листа металла, 0.004 м3 древесины, цена 50 руб.

Ограничения:
  металл:      0.04*x1 + 0.02*x2 <= 300
  древесина:   0.004*x1 + 0.004*x2 <= 60
  спрос:       x2 - x1 <= 3000   (штыковых не более чем на 3000 больше совковых)
  спрос:       x1 <= 15000       (совковых не больше 15000 в месяц)
  x1, x2 >= 0

Цель: максимизировать доход 60*x1 + 50*x2.
"""

from scipy.optimize import linprog

c = [-60, -50]

A_ub = [
    [0.04, 0.02],
    [0.004, 0.004],
    [-1, 1],
]
b_ub = [300, 60, 3000]


bounds = [(0, 15000), (0, None)]

result = linprog(c, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method="highs")

print("Статус:", result.message)
print(f"Совковых лопат (x1): {result.x[0]:.0f}")
print(f"Штыковых лопат (x2): {result.x[1]:.0f}")
print(f"Максимальный доход: {-result.fun:.2f} руб.")
